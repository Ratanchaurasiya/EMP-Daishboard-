export interface AssetRequestEmailPayload {
  requestId?: string;
  employeeName: string;
  employeeId: string;
  companyEmployeeNumber?: string;
  employeeEmail?: string;
  employeePhone?: string;
  department?: string;
  designation?: string;
  requestDate: string;
  urgency: 'Normal' | 'High' | 'Critical';
  items: Array<{
    assetType: string;
    customAssetName?: string;
    quantity: number;
    specifications?: string;
  }>;
  reason: string;
}

export function generateAssetRequestEmailContent(payload: AssetRequestEmailPayload) {
  const urgencyUpper = payload.urgency.toUpperCase();
  const requestId =
    payload.requestId || `REQ-${new Date().getFullYear()}-${Date.now().toString().slice(-4)}`;

  const totalItemsCount = payload.items.length;
  const totalUnits = payload.items.reduce((sum, item) => sum + (item.quantity || 1), 0);

  const subject = `[EQUIPMENT REQUEST - ${urgencyUpper}] ${payload.employeeName} (${payload.employeeId}) - ${totalUnits} Assets Requested`;

  const itemLines: string[] = [];
  payload.items.forEach((item, idx) => {
    const itemName = item.customAssetName ? `${item.assetType} (${item.customAssetName})` : item.assetType;
    const spec = item.specifications ? ` [Notes: ${item.specifications}]` : '';
    itemLines.push(`  ${idx + 1}. ${itemName} — Qty: ${item.quantity} unit(s)${spec}`);
  });

  const bodyLines = [
    `=====================================================`,
    `       OFFICIAL EMPLOYEE EQUIPMENT REQUISITION        `,
    `=====================================================`,
    ``,
    `REQUISITION DETAILS:`,
    `-----------------------------------------------------`,
    `Request ID:         ${requestId}`,
    `Date Submitted:     ${payload.requestDate}`,
    `Priority / Urgency: ${urgencyUpper}`,
    `Status:             Pending Admin Review & Allocation`,
    `Dispatched To:      ${IT_SUPPORT_EMAIL}`,
    ``,
    `EMPLOYEE DETAILS:`,
    `-----------------------------------------------------`,
    `Name:               ${payload.employeeName}`,
    `Employee ID:        ${payload.employeeId}`,
    payload.companyEmployeeNumber ? `Badge / Payroll #:  ${payload.companyEmployeeNumber}` : null,
    payload.department ? `Department:         ${payload.department}` : null,
    payload.designation ? `Designation:        ${payload.designation}` : null,
    payload.employeeEmail ? `Contact Email:      ${payload.employeeEmail}` : null,
    payload.employeePhone ? `Contact Phone:      ${payload.employeePhone}` : null,
    ``,
    `REQUESTED ASSETS & EQUIPMENT (${totalItemsCount} Types, ${totalUnits} Total Units):`,
    `-----------------------------------------------------`,
    ...itemLines,
    ``,
    `BUSINESS JUSTIFICATION & PURPOSE:`,
    `-----------------------------------------------------`,
    payload.reason,
    ``,
    `-----------------------------------------------------`,
    `Generated by:       AssetCore Enterprise Fleet Management`,
    `Notification Target: ${IT_SUPPORT_EMAIL}`,
    `Admin Action:       Review, Approve & Allocate from Inventory`,
    `=====================================================`,
  ].filter(line => line !== null);

  const body = bodyLines.join('\n');

  return {
    to: IT_SUPPORT_EMAIL,
    subject,
    body,
    requestId,
  };
}

